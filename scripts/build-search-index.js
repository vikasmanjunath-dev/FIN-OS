#!/usr/bin/env node
/**
 * build-search-index.js
 * Keeps js/finos-search.js complete without hand-editing.
 *
 * The curated INDEX in finos-search.js stays the source of truth for quality
 * titles/tags. Any page in html/ or calculators/ that the curated entries do not
 * cover is added to an AUTO block (between the AUTO-INDEX markers) using the
 * page's own <title>, meta description and file name.
 *
 *   node scripts/build-search-index.js          # rewrite the AUTO block
 *   node scripts/build-search-index.js --check  # exit 1 if the block is stale (CI)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FILE = path.join(ROOT, 'js', 'finos-search.js');
const START = '/* AUTO-INDEX:START — generated by scripts/build-search-index.js, do not edit by hand */';
const END = '/* AUTO-INDEX:END */';

// Keep in sync with SEARCH_EXEMPT in tests/static_audit.py.
const EXEMPT = /(detail\.html$|^html\/(readme|onboarding|start|login|chat|not-money)\.html$)/;

const read = (p) => fs.readFileSync(p, 'utf8');
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

function listPages() {
  const out = [];
  for (const f of fs.readdirSync(path.join(ROOT, 'html')).sort()) {
    if (f.endsWith('.html') && !f.startsWith('.')) out.push(`html/${f}`);
  }
  const calcRoot = path.join(ROOT, 'calculators');
  for (const d of fs.readdirSync(calcRoot).sort()) {
    const dir = path.join(calcRoot, d);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir).sort()) {
      if (f.endsWith('.html') && !f.startsWith('.')) out.push(`calculators/${d}/${f}`);
    }
  }
  return out;
}

const decode = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
const clean = (s) => decode(s).replace(/\s+/g, ' ').trim();

function describe(relPath) {
  const html = read(path.join(ROOT, relPath));
  const isRedirect = /http-equiv=["']refresh["']/i.test(html) && html.length < 3000;
  let title = (html.match(/<title>([\s\S]*?)<\/title>/i) || [, ''])[1];
  title = clean(title).replace(/\s*[|\-–—]\s*FIN[•\-·]?OS.*$/i, '').replace(/^FIN[•\-·]?OS\s*[|\-–—:]\s*/i, '').trim();
  const slug = path.basename(relPath, '.html');
  if (!title || /^FIN[•\-·]?OS$/i.test(title)) title = slug.replace(/[-_]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
  const dm = html.match(/<meta[^>]+name=["']description["'][^>]+content=(?:"([^"]*)"|'([^']*)')/i);
  let desc = dm ? clean(dm[1] || dm[2] || '') : '';
  if (!desc) desc = `${title} — FIN-OS ${relPath.startsWith('calculators/') ? 'calculator' : 'page'}`;
  if (desc.length > 120) desc = desc.slice(0, 117).replace(/\s+\S*$/, '') + '…';
  const words = new Set(`${title} ${slug.replace(/[-_]+/g, ' ')} ${relPath.startsWith('calculators/') ? relPath.split('/')[1] : ''}`.toLowerCase().split(/[^a-z0-9₹%&]+/).filter((w) => w.length > 2));
  return { isRedirect, title, desc, tags: [...words].slice(0, 8) };
}

function curatedUrls(src) {
  const before = src.includes(START) ? src.slice(0, src.indexOf(START)) : src;
  const set = new Set();
  for (const m of before.matchAll(/url\s*:\s*['"]([^'"]+)['"]/g)) set.add(path.posix.normalize(m[1].split(/[#?]/)[0]).replace(/^\.\.\//, ''));
  return set;
}

function buildBlock(src) {
  const have = curatedUrls(src);
  const lines = [];
  for (const p of listPages()) {
    if (have.has(p) || EXEMPT.test(p)) continue;
    const d = describe(p);
    if (d.isRedirect) continue; // the redirect target is what should be indexed
    const q = (s) => JSON.stringify(s);
    const cat = p.startsWith('calculators/') ? 'Calculators' : /^html\/learn-/.test(p) ? 'Learning' : 'Pages';
    lines.push(`    { title:${q(d.title)}, desc:${q(d.desc)}, url:${q('../' + p)}, cat:${q(cat)}, tags:${q(d.tags)} },`);
  }
  return `${START}\n${lines.join('\n')}${lines.length ? '\n' : ''}    ${END}`;
}

function main() {
  const check = process.argv.includes('--check');
  let src = read(FILE);
  if (!src.includes(START)) {
    // First run: insert the block right before the closing of the INDEX array.
    const idx = src.indexOf('];', src.indexOf('const INDEX'));
    if (idx < 0) throw new Error('INDEX array not found in finos-search.js');
    src = src.slice(0, idx) + `\n    ${START}\n    ${END}\n  ` + src.slice(idx);
  }
  const s = src.indexOf(START);
  const e = src.indexOf(END) + END.length;
  const next = src.slice(0, s) + buildBlock(src) + src.slice(e);
  const n = (next.slice(next.indexOf(START), next.indexOf(END)).match(/\{ title:/g) || []).length;
  if (check) {
    if (next !== read(FILE)) {
      console.error('✖ finos-search.js AUTO-INDEX block is stale — run: node scripts/build-search-index.js');
      process.exit(1);
    }
    console.log(`✔ search index up to date (${n} auto entries)`);
    return;
  }
  if (next !== read(FILE)) fs.writeFileSync(FILE, next);
  console.log(`✅ search index: ${n} auto-generated entries written to js/finos-search.js`);
}

main();
