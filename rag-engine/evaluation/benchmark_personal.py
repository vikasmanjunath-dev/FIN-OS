# ─────────────────────────── Index / run / cleanup ───────────────────────────

def _namespace_user(pid: str | None) -> str | None:
    return f"bench-{pid}" if pid else None


def seed() -> int:
    import config
    from embedding.encoder import embed_batch
    from storage.qdrant_store import ensure_collection, upsert_chunks
    from storage import sqlite_fts

    ensure_collection()
    n = 0
    for pid, p in PERSONAS.items():
        cards = make_cards(pid, p)
        texts = [c["text"] for c in cards]
        vecs = embed_batch(texts)
        ns = config.user_namespace(_namespace_user(pid))
        payloads = [{"text": c["text"], "namespace": ns, "doc_type": DOC_TYPE, "doc_title": c["title"],
                     "ingested_at": time.time()} for c in cards]
        ids = upsert_chunks(vecs, payloads)
        sqlite_fts.index_chunks(ids, texts, payloads)
        n += len(cards)
    return n


def cleanup() -> None:
    from storage.qdrant_store import delete_by_doc_type
    from storage import sqlite_fts
    delete_by_doc_type(DOC_TYPE)
    sqlite_fts.delete_by_doc_type(DOC_TYPE)


def _answer(query: str, user_id: str | None) -> tuple[str, list[str]]:
    from generation.prompt import build_prompt
    from generation.streamer import generate

    import config
    from retrieval.personal import retrieve_ranked
    ranked = retrieve_ranked(query, user_id, config.PROMPT_TOP_K)
    titles = [c["payload"].get("doc_title", "?") for c in ranked]
    return generate(build_prompt(query, ranked)), titles


def passes(answer: str, expect: list[list[str]], forbid: list[str]) -> bool:
    low = answer.lower()
    if forbid and any(f.lower() in low for f in forbid):
        return False
    return all(any(alt.lower() in low for alt in group) for group in expect)


def run(categories: list[str] | None = None, verbose: bool = True) -> dict:
    qs = [q for q in build_questions() if categories is None or q["category"] in categories]
    results, by_cat = [], {}
    try:                                    # seed inside the try: a failure half-way through seeding must still clean up
        seeded = seed()
        if verbose:
            print(f"seeded {seeded} fact cards for {len(PERSONAS)} personas; running {len(qs)} questions")
        for q in qs:
            t0 = time.time()
            try:
                ans, titles = _answer(q["query"], _namespace_user(q["user"]))
            except Exception as e:  # keep going; a crash is a failed question, not a crashed run
                ans, titles = f"[ERROR: {e}]", []
            ok = passes(ans, q["expect"], q["forbid"])
            by_cat.setdefault(q["category"], []).append(ok)
            results.append({"id": q["id"], "category": q["category"], "user": q["user"], "query": q["query"],
                            "pass": ok, "latency_sec": round(time.time() - t0, 1),
                            "retrieved": titles, "answer_excerpt": ans[:240]})
            if verbose:
                print(f"[{q['id']}][{'PASS' if ok else 'FAIL'}] ({results[-1]['latency_sec']}s) {q['query'][:68]}")
                if not ok:
                    print(f"    expect={[g[:3] for g in q['expect']]} forbid={q['forbid'][:3]}")
                    print(f"    retrieved={titles}")
                    print(f"    got={ans[:200]}")
    finally:
        cleanup()

    total = len(qs)
    passed = sum(r["pass"] for r in results)
    if verbose:
        print("=" * 60)
        print(f"PERSONAL OVERALL: {passed}/{total} ({100 * passed / max(1, total):.1f}%)")
        for cat, v in sorted(by_cat.items()):
            print(f"  {cat:8s}: {sum(v)}/{len(v)}")
    return {"total": total, "passed": passed, "pass_rate": round(passed / max(1, total), 3),
            "by_category": {c: {"passed": sum(v), "total": len(v), "rate": round(sum(v) / len(v), 3)} for c, v in by_cat.items()},
            "results": results}


