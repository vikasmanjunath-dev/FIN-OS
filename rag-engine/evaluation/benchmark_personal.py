"""
FIN-OS RAG personalized benchmark — added October 15 2026.

The 100-question public benchmark (benchmark.py) only exercises the `public`
namespace. This file adds questions that must be answered from a *person's own
data* (the `user:{id}` namespace), plus the negative cases that matter most for
a personal assistant: not inventing data the user never gave (abstention), and
never leaking one person's data to another or to an anonymous caller (isolation).

How it works
  1. Four synthetic personas with fixed three-month ledgers (Jul-Sep 2026).
  2. For each persona, plain-language "fact cards" are generated BY CODE from the
     ledger (docs/RAG_KNOWLEDGE_BASE.md planned this shape: numbers are computed,
     never typed by hand, so every expected answer is derivable from the ledger).
  3. Cards are embedded and indexed into `user:bench-<persona>` in both Qdrant and
     the FTS5 index, with doc_type `bench_fact_card`, exactly like
     evaluation/test_namespace_isolation.py seeds its fixture.
  4. Each question runs the SAME pipeline /api/query runs:
        hybrid_retrieve -> rerank(top_k=3) -> build_prompt -> generate
     in-process. It bypasses only the HTTP Supabase token check, because a
     benchmark has no real session token (the auth check has its own tests).
  5. Cards are deleted from both stores in `finally`, so the production index is
     left exactly as it was found.

Scoring is the same blunt substring rule as benchmark.py, extended with:
  expect : list of groups; every group needs at least one alternative present
  forbid : substrings that must NOT appear (isolation / no-leak checks)
Money is written many ways by the model (the system prompt asks for L/Cr/K), so
each number expands to the plausible spellings via money_variants().

Run:  cd rag-engine && .venv/bin/python evaluation/benchmark_personal.py [--json out.json] [CATEGORY ...]
      Needs Ollama (embedding + generation) and Qdrant. If the rag-engine server
      is running on this machine, the reranker model is loaded a second time;
      on a 24 GB machine that is better done with the server stopped.
"""
