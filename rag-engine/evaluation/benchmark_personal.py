# ─────────────────────────── Formatting helpers ──────────────────────────────

def indian_group(n: int) -> str:
    """1400000 -> '14,00,000' (lakh/crore grouping used across FIN-OS)."""
    s = str(abs(int(n)))
    if len(s) <= 3:
        out = s
    else:
        head, tail = s[:-3], s[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        out = ",".join(parts + [tail])
    return ("-" if n < 0 else "") + out


def inr(n: int) -> str:
    return "₹" + indian_group(n)


def money_variants(n: int) -> list[str]:
    """Plausible spellings of an amount: 11,200 / 11200 / 11.2K / 1.4 L / 1.4 lakh ..."""
    n = abs(int(n))
    v = {indian_group(n), f"{n:,}", str(n)}
    if n >= 100000:
        lakh = n / 100000
        for f in (f"{lakh:.2f}", f"{lakh:.1f}", f"{lakh:g}"):
            v |= {f"{f} L", f"{f}L", f"{f} lakh", f"{f} Lakh", f"{f} lacs"}
    if n >= 1000 and n % 100 == 0:
        k = n / 1000
        v |= {f"{k:g}K", f"{k:g}k", f"{k:g} K", f"{k:g} thousand"}
    if n >= 10_000_000:
        cr = n / 10_000_000
        v |= {f"{cr:g} Cr", f"{cr:g} crore", f"{cr:g}Cr"}
    return sorted(v)


def pct_variants(x: float) -> list[str]:
    return sorted({f"{x:.2f}", f"{x:.1f}", f"{x:.0f}%", f"{x:.0f} %", f"{math.floor(x * 10) / 10:.1f}"})


# ─────────────────────────── Derived numbers ─────────────────────────────────

def total_spend(p: dict, m: str) -> int:
    return sum(p["spend"][m].values())


def saving_total(p: dict) -> int:
    return sum(p["saving"].values())


def savings_rate(p: dict, m: str) -> float:
    """(income - spending) / income, in percent. Investments count as saved."""
    inc = p["income"][m]
    return round((inc - total_spend(p, m)) / inc * 100, 1)


def delta(p: dict, cat: str, a: str, b: str) -> int:
    return p["spend"][b].get(cat, 0) - p["spend"][a].get(cat, 0)


def biggest_move(p: dict, a: str, b: str, up: bool = True) -> tuple[str, int]:
    cats = set(p["spend"][a]) | set(p["spend"][b])
    moves = {c: delta(p, c, a, b) for c in cats}
    cat = max(moves, key=moves.get) if up else min(moves, key=moves.get)
    return cat, moves[cat]


# ─────────────────────────── Fact-card generation ────────────────────────────

def make_cards(pid: str, p: dict) -> list[dict]:
    """Return [{title, text}], every card kept under ~480 chars because the
    prompt builder truncates each retrieved chunk to 500 chars."""
    cards: list[dict] = []
    prev = None
    for m in MONTHS:
        spend = p["spend"][m]
        tot = total_spend(p, m)
        inc = p["income"][m]
        rate = savings_rate(p, m)
        line = (f"{p['name']}'s summary for {MONTH_NAME[m]}: income {inr(inc)}, total spending {inr(tot)}, "
                f"savings rate {rate}%.")
        if p["saving"]:
            line += " SIP investments are tracked separately: " + ", ".join(f"{k} {inr(v)} a month" for k, v in p["saving"].items()) + "."
        if prev:
            cat_up, d_up = biggest_move(p, prev, m, up=True)
            cat_dn, d_dn = biggest_move(p, prev, m, up=False)
            line += (f" Versus {MONTH_NAME[prev]}: total spending {'rose' if tot >= total_spend(p, prev) else 'fell'} by "
                     f"{inr(abs(tot - total_spend(p, prev)))}")
            if d_up > 0:
                line += f"; biggest increase {cat_up} {inr(d_up)}"
            if d_dn < 0:
                line += f"; biggest decrease {cat_dn} {inr(abs(d_dn))}"
            line += "."
        cards.append({"title": f"{p['name']} - {MONTH_NAME[m]} summary", "text": line})

        cats = "; ".join(f"{c} {inr(a)}" for c, a in spend.items())
        cards.append({"title": f"{p['name']} - {MONTH_NAME[m]} spending by category",
                      "text": f"{p['name']}'s spending by category in {MONTH_NAME[m]}: {cats}."})
        prev = m

    liab = "; ".join(f"{l['name']} {inr(l['emi'])} per month" for l in p["liabilities"]) or "no loans recorded"
    rent = p["spend"][MONTHS[-1]].get("Housing")
    profile = (f"{p['name']} profile: age {p['age']}, lives in {p['city']}, {p['job']}. "
               f"Monthly income {inr(p['income'][MONTHS[-1]])}. Monthly housing or rent cost {inr(rent)}. Liabilities: {liab}. "
               f"Emergency fund saved: {inr(p['emergency_fund'])}. "
               f"Not provided / unknown: {', '.join(p['gaps'])}.")
    cards.append({"title": f"{p['name']} - profile", "text": profile})

    if p["goals"]:
        gl = " ".join(
            f"Goal '{g['name']}': target {inr(g['target'])} by {g['by']}; saved so far {inr(g['funded'])}; "
            f"remaining {inr(g['target'] - g['funded'])}." for g in p["goals"])
        cards.append({"title": f"{p['name']} - goals", "text": f"{p['name']}'s goals. {gl}"})
    else:
        cards.append({"title": f"{p['name']} - goals", "text": f"{p['name']} has not set any financial goals yet."})

    for c in cards:
        assert len(c["text"]) <= 500, f"card too long ({len(c['text'])}): {c['title']}"
    return cards


