# ── dialogs: focus in, Tab trapped, Esc closes and restores focus (needs the js/finos-a11y.js patch) ───────────────
DIALOGS = [
    ("arya", "html/home.html", 1280, "#sb-arya-btn", "#arya-sp-panel"),
    ("voice-popup", "html/home.html", 1280, "#finos-fab", "#finos-popup"),
    ("alerts", "html/home.html", 1280, "#finos-alert-bell", "#finos-alert-drawer"),
    ("insight", "html/dashboard.html", 1280, ".ic-card", "#ic-modal-overlay"),
    ("mobile-nav", "html/home.html", 390, ".mob-ham", ".sidebar"),
]


def _dialog_run(browser, base, spec, patch):
    _, path, width, opener, panel = spec
    ctx, pg = _page(browser, base, path, width=width, height=820, patch=patch)
    inside = "(s)=>{const r=document.querySelector(s),a=document.activeElement;return !!(r&&a&&r.contains(a))}"
    pg.focus(opener)
    pg.keyboard.press("Enter")
    pg.wait_for_timeout(900)
    moved = pg.evaluate(inside, panel)
    leaks = 0
    for _ in range(20):
        pg.keyboard.press("Tab")
        pg.wait_for_timeout(25)
        if not pg.evaluate(inside, panel):
            leaks += 1
    # Esc typed while focus is inside the voice popup's <iframe> never reaches this document (that page would have to
    # postMessage it); put focus back on the panel's own first control, as a user shift-tabbing out of the frame would.
    if pg.evaluate("document.activeElement && document.activeElement.tagName === 'IFRAME'"):
        pg.evaluate("(s)=>{const f=[...document.querySelector(s).querySelectorAll('button,a[href]')][0]; f && f.focus()}", panel)
    pg.keyboard.press("Escape")
    pg.wait_for_timeout(800)
    active = pg.evaluate("document.activeElement === document.body ? 'body' : (document.activeElement.id || document.activeElement.className)")
    restored = pg.evaluate("(s)=>{const o=document.querySelector(s);return !!o && document.activeElement===o}", opener)
    ctx.close()
    return moved, leaks, restored, active


@pytest.mark.parametrize("spec", DIALOGS, ids=[d[0] for d in DIALOGS])
def test_dialogs_trap_and_restore_focus_with_proposed_a11y_patch(env, spec):
    base, browser = env
    moved, leaks, restored, active = _dialog_run(browser, base, spec, patch=True)
    assert moved, "focus did not move into the panel"
    assert leaks == 0, f"Tab left the panel {leaks} times"
    assert restored, f"focus not restored to the opener (on {active})"


@pytest.mark.xfail(reason="needs docs/agent-notes/web-a11y-leftovers-finos-a11y.diff applied to js/finos-a11y.js (js/ is owned elsewhere)", strict=False)
@pytest.mark.parametrize("spec", DIALOGS, ids=[d[0] for d in DIALOGS])
def test_dialogs_trap_and_restore_focus_in_repo_js(env, spec):
    base, browser = env
    moved, leaks, restored, _ = _dialog_run(browser, base, spec, patch=False)
    assert moved and leaks == 0 and restored


